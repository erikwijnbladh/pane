// Regenerates app/src/demoFiles.ts from workspace/src/components so the
// hosted demo's in-memory files always match what's on disk.
// Run: npm run sync:demo (also runs automatically as part of npm run build)
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const componentsDir = path.join(root, 'workspace/src/components')
const outFile = path.join(root, 'app/src/demoFiles.ts')

const files = fs.readdirSync(componentsDir)
  .filter(f => /^[A-Za-z][A-Za-z0-9_-]*\.(tsx|ts)$/.test(f))
  .sort()

const entries = files.map(f => {
  const content = fs.readFileSync(path.join(componentsDir, f), 'utf8')
  return `  ${JSON.stringify(f)}: ${JSON.stringify(content)},`
})

const out = `// Generated by scripts/sync-demo-files.mjs — do not edit by hand.
export const DEMO_FILE_CONTENTS: Record<string, string> = {
${entries.join('\n')}
}
`

fs.writeFileSync(outFile, out)
console.log(`Wrote ${files.length} files to app/src/demoFiles.ts: ${files.join(', ')}`)
